"""TMLR follow-up — write configs + manifest from the design, and prove them.

    python scripts/tmlr_configs.py --write          # configs/tmlr/<exp>/*.yaml + manifest.json
    python scripts/tmlr_configs.py --check          # budgets (closed form vs built) + recipe control
    python scripts/tmlr_configs.py --select-e5 DIR  # plan A8 selection from E5-val results
    python scripts/tmlr_configs.py --freeze         # refuse any later change to a written config

Every generated config is a MINIMAL override of the parent the original grid
(or the TMLR parents) used: seed, k_shot, the adapter block, the stream flag,
loss knobs for E5, and bookkeeping. The recipe arrives by inheritance, and
`control_guard` proves it on the merged configs.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from contextlib import contextmanager
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
for p in (str(REPO), str(REPO / "scripts")):
    if p not in sys.path:
        sys.path.insert(0, p)

import tmlr_design as T  # noqa: E402
from src.utils.config import ConfigDict, _deep_merge, load_config  # noqa: E402

FROZEN_MARKER = Path("configs/tmlr/FROZEN")
MANIFEST = Path("configs/tmlr/manifest.json")
E5_SELECTED = Path("configs/tmlr/e5_selected.yaml")
#: Plan A8 tie rule: VAL ECE within this of the best -> prefer higher VAL accuracy.
E5_TIE = 0.002
GENERATED_ADAPTER_EXPS = ("e1", "e2", "e3a", "e3b")


# =====================================================================
# Config documents
# =====================================================================
def config_doc(s: T.RunSpec, cfg_dir: Path) -> dict:
    doc: dict = {
        "extends": os.path.relpath(REPO / s.parent, cfg_dir),
        "seed": int(s.seed),
        "dataset": {"k_shot": int(s.k_shot)},
        "trainer": {"vary_train_stream_with_seed": bool(s.vary_stream)},
    }
    if s.experiment in GENERATED_ADAPTER_EXPS:
        doc["adapter"] = T.adapter_block(s.backbone, s.arm, s.rank_spec)
    if s.loss_overrides:
        doc["loss"] = {k: float(v) for k, v in s.loss_overrides}
    doc["output"] = {"run_tag": s.run_id, "results_dir": f"results/tmlr/{s.experiment}"}
    doc["wandb"] = {"disabled": True, "mode": "disabled", "group": f"tmlr-{s.experiment}",
                    "tags": ["tmlr", s.experiment]}
    return doc


def merged_config(s: T.RunSpec) -> ConfigDict:
    """Exactly what load_config would return for the written file."""
    doc = config_doc(s, (REPO / s.config).parent)
    doc.pop("extends")
    base = dict(load_config(REPO / s.parent))
    return ConfigDict(_deep_merge(base, doc))


def merged_sha256(s: T.RunSpec) -> str:
    blob = json.dumps(merged_config(s), sort_keys=True, default=str)
    return hashlib.sha256(blob.encode()).hexdigest()


def write_configs(specs: list[T.RunSpec], root: Path = REPO, *, manifest: bool = True) -> int:
    """Write one YAML per runnable spec (wave >= 0) and the manifest."""
    frozen = (root / FROZEN_MARKER).exists()
    n = 0
    runnable = [s for s in specs if s.wave >= 0]
    for s in runnable:
        path = root / s.config
        path.parent.mkdir(parents=True, exist_ok=True)
        text = ("# AUTO-GENERATED by scripts/tmlr_configs.py -- do not hand-edit.\n"
                f"# {s.experiment}: {s.dataset} {s.k_shot}-shot {s.backbone} {s.arm} "
                f"level={s.level} rank={s.rank_spec} {s.head} seed={s.seed} "
                f"vary_stream={s.vary_stream}\n"
                + yaml.safe_dump(config_doc(s, path.parent), sort_keys=False))
        if path.exists() and path.read_text() != text and frozen:
            raise RuntimeError(f"{FROZEN_MARKER} exists; refusing to change {s.config}")
        path.write_text(text)
        n += 1
    if manifest:
        entries = []
        for s in runnable:
            e = s.to_json()
            e["merged_config_sha256"] = merged_sha256(s)
            entries.append(e)
        entries.sort(key=lambda e: e["run_id"])
        (root / MANIFEST).parent.mkdir(parents=True, exist_ok=True)
        (root / MANIFEST).write_text(json.dumps({"runs": entries}, indent=1, sort_keys=True))
    return n


# =====================================================================
# Budgets: closed form vs instantiated (no weight download)
# =====================================================================
@contextmanager
def _offline_backbones():
    import src.models.bpeft_model as bm
    from src.backbones import build_backbone as real
    orig = bm.build_backbone
    bm.build_backbone = lambda name, pretrained=True: real(name, pretrained=False)
    try:
        yield
    finally:
        bm.build_backbone = orig


def assert_budgets(specs: list[T.RunSpec]) -> dict:
    from src.models import build_model
    from src.utils import count_trainable_params
    failures, seen = [], {}
    with _offline_backbones():
        for s in specs:
            if s.wave < 0:
                continue
            key = (s.backbone, s.arm, s.rank_spec, s.head)
            if key in seen:
                continue
            built = int(count_trainable_params(build_model(merged_config(s))))
            seen[key] = built
            if built != s.expected_n_params:
                failures.append(f"{s.run_id}: built {built} != expected {s.expected_n_params}")
    levels = []
    for (bb, lvl), arms in T.LEVELS.items():
        params = {a: T.expected_params(bb, a, rs, "softmax") for a, rs in arms.items()}
        spread = max(params.values()) / min(params.values()) - 1
        levels.append({"backbone": bb, "level": lvl, "params": params, "spread": spread})
        if spread > T.MAX_LEVEL_SPREAD:
            failures.append(f"{bb} level {lvl}: spread {spread:.4f} > {T.MAX_LEVEL_SPREAD}")
    return {"ok": not failures, "failures": failures, "n_checked": len(seen), "levels": levels}


# =====================================================================
# Recipe control on merged configs
# =====================================================================
def _flatten(d, prefix="") -> dict:
    out = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(_flatten(v, key + "."))
        else:
            out[key] = json.dumps(v, sort_keys=True, default=str)
    return out


_ALWAYS_ALLOWED = ("adapter.", "seed", "output.", "wandb.", "dataset.k_shot",
                   "trainer.vary_train_stream_with_seed")


def _allowed(key: str, extra=()) -> bool:
    return any(key == a or key.startswith(a) for a in _ALWAYS_ALLOWED + tuple(extra))


def control_guard(specs: list[T.RunSpec]) -> dict:
    """Within a comparison group, merged configs may differ only in allowed keys.

    Groups: (experiment, dataset, backbone, head) for the generated-adapter
    experiments and E5-val (loss knobs allowed there). E5 is compared one-to-one
    with the grid config it extends (loss knobs allowed). E4 is checked by
    tests/test_tmlr_design.py::test_e4_wraps_original_grid.
    """
    failures, groups = [], {}
    for s in specs:
        if s.wave < 0 or s.experiment == "e4":
            continue
        if s.experiment == "e5":
            new = _flatten(merged_config(s))
            old = _flatten(load_config(REPO / s.parent))
            bad = sorted(k for k in set(new) | set(old)
                         if new.get(k) != old.get(k) and not _allowed(k, ("loss.",)))
            if bad:
                failures.append(f"{s.run_id}: differs from its grid parent in {bad}")
            continue
        groups.setdefault((s.experiment, s.dataset, s.backbone, s.head), []).append(s)
    for key, members in groups.items():
        extra = ("loss.",) if key[0] == "e5val" else ()
        flats = [_flatten(merged_config(m)) for m in members]
        keys = set().union(*flats)
        bad = sorted(k for k in keys if not _allowed(k, extra)
                     and len({f.get(k) for f in flats}) > 1)
        if bad:
            failures.append(f"group {key}: recipe keys differ across arms: {bad}")
    return {"ok": not failures, "failures": failures, "n_groups": len(groups)}


# =====================================================================
# E5 selection (plan A8) — VAL only
# =====================================================================
def choose_e5(records: list[dict]) -> dict:
    """records: {kl_weight_max, prior_per_class, val_ece, val_acc}. Lowest VAL
    ECE; within E5_TIE of the best, the higher VAL accuracy wins."""
    if not records:
        raise ValueError("no E5-val records")
    best = min(r["val_ece"] for r in records)
    tied = [r for r in records if r["val_ece"] - best < E5_TIE]
    pick = sorted(tied, key=lambda r: (-r["val_acc"], r["val_ece"]))[0]
    current = (pick["kl_weight_max"] == T.CURRENT_EDL["kl_weight_max"]
               and pick["prior_per_class"] == T.CURRENT_EDL["prior_per_class"])
    return {"kl_weight_max": float(pick["kl_weight_max"]),
            "prior_per_class": float(pick["prior_per_class"]),
            "skipped": bool(current),
            "rule": f"lowest VAL ECE; ties within {E5_TIE} -> higher VAL accuracy",
            "candidates": records}


def select_e5(results_dir: Path) -> dict:
    by_id = {s.run_id: s for s in T.build_design(e5_selection=None) if s.experiment == "e5val"}
    recs = []
    for rid, s in by_id.items():
        p = results_dir / rid / "metrics.json"
        if not p.exists():
            raise FileNotFoundError(f"E5-val incomplete: {p}")
        m = json.load(open(p))
        lo = dict(s.loss_overrides)
        recs.append({"run_id": rid, "kl_weight_max": lo["kl_weight_max"],
                     "prior_per_class": lo["prior_per_class"],
                     "val_ece": m["val_ece_pooled__evidential_native"],
                     "val_acc": m["val_accuracy__evidential_native"]})
    sel = choose_e5(recs)
    (REPO / E5_SELECTED).write_text(yaml.safe_dump(sel, sort_keys=False))
    return sel


# =====================================================================
# CLI
# =====================================================================
def _print_check(b: dict, g: dict, specs) -> None:
    from collections import Counter
    print("runs per experiment:", dict(sorted(Counter(s.experiment for s in specs).items())))
    print("runs per wave      :", dict(sorted(Counter(s.wave for s in specs).items())))
    print(f"\nbudgets: {b['n_checked']} distinct arms built and compared -> "
          f"{'OK' if b['ok'] else 'FAIL'}")
    for lv in b["levels"]:
        arms = "  ".join(f"{a}={p:,}" for a, p in lv["params"].items())
        print(f"  {lv['backbone']:<18} {lv['level']}  {arms}   spread {lv['spread'] * 100:.2f}%")
    print(f"\ncontrol_guard: {g['n_groups']} groups -> {'OK' if g['ok'] else 'FAIL'}")
    for f in b["failures"] + g["failures"]:
        print("  FAIL", f)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--select-e5", type=Path)
    ap.add_argument("--freeze", action="store_true")
    a = ap.parse_args(argv)
    if a.select_e5:
        sel = select_e5(a.select_e5)
        print(yaml.safe_dump(sel, sort_keys=False))
    specs = T.build_design()
    if a.write:
        print(f"wrote {write_configs(specs)} configs + {MANIFEST}")
    if a.check:
        b, g = assert_budgets(specs), control_guard(specs)
        _print_check(b, g, specs)
        if not (b["ok"] and g["ok"]):
            return 1
    if a.freeze:
        (REPO / FROZEN_MARKER).write_text("Configs frozen for the TMLR waves. Do not edit.\n")
        print(f"wrote {FROZEN_MARKER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
